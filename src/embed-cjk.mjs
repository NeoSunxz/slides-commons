#!/usr/bin/env node
// embed-cjk.mjs: embed the CJK web fonts a finished slide deck needs, so the deck still renders
// in its intended fonts offline and in regions where Google Fonts is unreachable.
//
//   node fonts/embed-cjk.mjs <deck.html>            embed (idempotent; re-run after every text edit)
//   node fonts/embed-cjk.mjs <deck.html> --dry-run  plan and report only, change nothing
//   node fonts/embed-cjk.mjs <deck.html> --no-subset  never shrink shards, even if pyftsubset exists
//
// What it does
//   1. Reads every character of the deck (all of the file except base64 data and its own block;
//      HTML entities and CSS/JS escapes are decoded) and the CJK font families + weights the deck
//      requests from Google Fonts (<link> or @import).
//   2. Picks, per family and weight, every font shard (a unicode-range slice of the font, the same
//      slicing Google Fonts uses) that contains at least one of those characters.
//   3. Downloads those shards (this site, then jsDelivr; no other host) and writes them into the deck
//      as base64 @font-face rules, each with its unicode-range, between two marker comments.
//      The deck's Google Fonts link stays as a fallback for characters added later.
//   4. Checks that every CJK character is covered, and prints a summary.
//
// Zero dependencies; Node 18 or newer; no shell. If `pyftsubset` (fonttools) is on PATH each
// shard is also cut down to the characters actually used (its unicode-range then narrows to
// them, so characters added later fall through to the Google Fonts link, never to a missing glyph).
//
// Exit codes: 0 ok | 1 usage or file error | 2 a CJK character no embedded font has |
//             3 some shards could not be downloaded (the rest is embedded) | 4 no CJK font link found

import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import zlib from 'node:zlib';
import { execFileSync } from 'node:child_process';

const BEGIN = '<!-- slides-commons:cjk-embed:begin (generated by fonts/embed-cjk.mjs; re-run it after text edits, do not edit by hand) -->';
const END = '<!-- slides-commons:cjk-embed:end -->';
const BLOCK_RE = /<!-- slides-commons:cjk-embed:begin[\s\S]*?<!-- slides-commons:cjk-embed:end -->\s*/g;

const HERE = path.dirname(fileURLToPath(import.meta.url));

// --- arguments ----------------------------------------------------------------------------

const args = process.argv.slice(2);
const flag = (name) => { const i = args.indexOf(name); if (i < 0) return false; args.splice(i, 1); return true; };
const opt = (name) => { const i = args.indexOf(name); if (i < 0) return null; const v = args[i + 1]; args.splice(i, 2); return v ?? null; };
