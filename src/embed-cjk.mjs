function usedChars(text) {
  // Drop base64 payloads (they are ASCII anyway, but huge) and any previous embedded block.
  const t = text.replace(BLOCK_RE, '').replace(/data:[a-z0-9.+\-/]+;base64,[A-Za-z0-9+/=_-]+/gi, '');
  const set = new Set();
  for (const ch of t) set.add(ch.codePointAt(0));
  // Decoded escapes, added on top of the literal characters (over-approximation is safe).
  const add = (cp) => { if (cp > 0 && cp <= 0x10ffff && !(cp >= 0xd800 && cp <= 0xdfff)) set.add(cp); };
  for (const m of t.matchAll(/&#x([0-9a-f]+);/gi)) add(parseInt(m[1], 16));
  for (const m of t.matchAll(/&#(\d+);/g)) add(parseInt(m[1], 10));
  for (const m of t.matchAll(/&([a-z][a-z0-9]*);/gi)) if (NAMED[m[1]] !== undefined) add(NAMED[m[1]]);
  for (const m of t.matchAll(/\\u\{([0-9a-f]{1,6})\}/gi)) add(parseInt(m[1], 16));
  const pairs = [...t.matchAll(/\\u([0-9a-f]{4})/gi)].map((m) => parseInt(m[1], 16));
  for (let i = 0; i < pairs.length; i++) {
    const hi = pairs[i];
    if (hi >= 0xd800 && hi <= 0xdbff && pairs[i + 1] >= 0xdc00 && pairs[i + 1] <= 0xdfff) add(0x10000 + ((hi - 0xd800) << 10) + (pairs[i + 1] - 0xdc00));
    else add(hi);
  }
  for (const m of t.matchAll(/\\([0-9a-f]{1,6})(?=[\s"'\\;)}]|$)/gi)) add(parseInt(m[1], 16)); // CSS escapes
  return [...set].sort((a, b) => a - b);
}

// CJK characters whose font coverage must be complete (letters, kana, hangul, punctuation, full-width forms).
const CJK_RE = /[\u2E80-\u2FDF\u3000-\u30FF\u3100-\u312F\u3190-\u31FF\u3200-\u33FF\u3400-\u4DBF\u4E00-\u9FFF\uA960-\uA97F\uAC00-\uD7FF\uF900-\uFAFF\uFE10-\uFE1F\uFE30-\uFE4F\uFF00-\uFFEF\u{20000}-\u{2FA1F}\u{30000}-\u{3134F}]/u;
const IGNORED_RE = /[\p{Z}\p{C}\p{M}]/u; // spaces, controls, joiners, variation selectors, combining marks
const isCjk = (cp) => { const ch = String.fromCodePoint(cp); return CJK_RE.test(ch) && !IGNORED_RE.test(ch); };

// --- unicode-range helpers -----------------------------------------------------------------

function parseRange(str) {
  const out = [];
  for (const part of str.split(',')) {
    const m = part.trim().match(/^U\+([0-9a-f?]+)(?:-([0-9a-f]+))?$/i);
    if (!m) continue;
    if (m[1].includes('?')) out.push([parseInt(m[1].replace(/\?/g, '0'), 16), parseInt(m[1].replace(/\?/g, 'f'), 16)]);
    else out.push([parseInt(m[1], 16), parseInt(m[2] ?? m[1], 16)]);
  }
  return out.sort((a, b) => a[0] - b[0]);
}
function rangeHas(ranges, cp) {
  let lo = 0, hi = ranges.length - 1;
  // ranges may overlap in odd tables: scan the neighbourhood after a binary search for the last start <= cp
  while (lo < hi) { const mid = (lo + hi + 1) >> 1; if (ranges[mid][0] <= cp) lo = mid; else hi = mid - 1; }
  for (let i = lo; i >= 0 && i >= lo - 4; i--) if (ranges[i][0] <= cp && cp <= ranges[i][1]) return true;
  return false;
}
function formatRange(cps) {
  const parts = [];
  for (let i = 0; i < cps.length;) {
    let j = i;
    while (j + 1 < cps.length && cps[j + 1] === cps[j] + 1) j++;
    const h = (n) => 'U+' + n.toString(16);
    parts.push(j > i ? `${h(cps[i])}-${j === i ? '' : cps[j].toString(16)}` : h(cps[i]));
    i = j + 1;
  }
  return parts.join(',');
}

// --- font requests in the deck -------------------------------------------------------------

function requestedFamilies(text) {
  const t = text.replace(BLOCK_RE, '');
  const urls = [...t.matchAll(/https:\/\/fonts\.googleapis\.com\/css2?\?[^"'`\s)<>]+/g)].map((m) => m[0].replace(/&amp;/g, '&'));
  const want = new Map(); // family -> Set(weights)  (null = "any available", for ranges handled below)
  const wanted = [];
  for (const raw of urls) {
    let u;
    try { u = new URL(raw); } catch { continue; }
    for (const param of u.searchParams.getAll('family')) {
      const [name, spec] = param.split(':');
      const family = name.replace(/\+/g, ' ');
      const items = []; // [lo, hi]
      if (!spec) items.push([400, 400]);
      else if (spec.includes('@')) {
        const [axes, tuples = ''] = spec.split('@');
        const ax = axes.split(',');
        const wi = ax.indexOf('wght');
        for (const tuple of tuples.split(';').filter(Boolean)) {
          const v = tuple.split(',');
          if (wi < 0) { items.push([400, 400]); continue; }
          if (ax.includes('ital') && v[ax.indexOf('ital')] === '1') continue; // CJK families have no italics
          const [lo, hi = lo] = (v[wi] ?? '400').split('..').map(Number);
          if (Number.isFinite(lo) && Number.isFinite(hi)) items.push([lo, hi]);
        }
        if (!items.length) items.push([400, 400]);
      } else { // css v1: Name:400,700,400i
        for (const w of spec.split(',')) if (/^\d+$/.test(w)) items.push([Number(w), Number(w)]);
        if (!items.length) items.push([400, 400]);
      }
      wanted.push({ family, items });
    }
  }
  for (const { family, items } of wanted) {
    if (!want.has(family)) want.set(family, []);
    want.get(family).push(...items);
  }
  return want;
}


// --- reading a woff2 file's character map (to verify what a shard really contains) ---------------
// Only the cmap table is needed; it is never transformed in woff2, so decompressing the table
// stream and slicing out cmap is enough.

function woff2Cmap(buf) {
  if (buf.length < 48 || buf.toString('latin1', 0, 4) !== 'wOF2') throw new Error('not a woff2 file');
  const numTables = buf.readUInt16BE(12);
  const compressedLen = buf.readUInt32BE(20);
  let pos = 48;
  const base128 = () => { let v = 0; for (let i = 0; i < 5; i++) { const b = buf[pos++]; v = v * 128 + (b & 0x7f); if (!(b & 0x80)) return v; } throw new Error('bad woff2 directory'); };
  const dir = [];
  for (let i = 0; i < numTables; i++) {
    const flags = buf[pos++];
    const idx = flags & 0x3f;
    const tag = idx === 63 ? (pos += 4, buf.toString('latin1', pos - 4, pos)) : idx === 0 ? 'cmap' : idx === 10 ? 'glyf' : idx === 11 ? 'loca' : idx === 3 ? 'hmtx' : `#${idx}`;
    const version = flags >> 6;
    const orig = base128();
    const transformed = tag === 'glyf' || tag === 'loca' ? version === 0 : version !== 0;
    dir.push({ tag, length: transformed ? base128() : orig });
  }
  const data = zlib.brotliDecompressSync(buf.subarray(pos, pos + compressedLen));
  let off = 0, cmap = null;
  for (const t of dir) { if (t.tag === 'cmap') cmap = data.subarray(off, off + t.length); off += t.length; }
  const out = new Set();
  if (!cmap) return out;
  const n = cmap.readUInt16BE(2);
  for (let i = 0; i < n; i++) {
    const platform = cmap.readUInt16BE(4 + i * 8), enc = cmap.readUInt16BE(6 + i * 8), o = cmap.readUInt32BE(8 + i * 8);
    if (!(platform === 0 || (platform === 3 && (enc === 1 || enc === 10)))) continue;
    const format = cmap.readUInt16BE(o);
    if (format === 4) {
      const segX2 = cmap.readUInt16BE(o + 6), seg = segX2 / 2;
      const endAt = o + 14, startAt = endAt + segX2 + 2, deltaAt = startAt + segX2, rangeAt = deltaAt + segX2;
      for (let k = 0; k < seg; k++) {
        const end = cmap.readUInt16BE(endAt + 2 * k), start = cmap.readUInt16BE(startAt + 2 * k);
        const delta = cmap.readUInt16BE(deltaAt + 2 * k), ro = cmap.readUInt16BE(rangeAt + 2 * k);
        for (let c = start; c <= end && c < 0xffff; c++) {
          let gid;
          if (ro === 0) gid = (c + delta) & 0xffff;
          else { const a = rangeAt + 2 * k + ro + 2 * (c - start); gid = a + 1 < cmap.length ? cmap.readUInt16BE(a) : 0; if (gid) gid = (gid + delta) & 0xffff; }
          if (gid) out.add(c);
        }
      }
    } else if (format === 12) {
      const groups = cmap.readUInt32BE(o + 12);
      for (let k = 0; k < groups; k++) {
        const g = o + 16 + k * 12, start = cmap.readUInt32BE(g), end = cmap.readUInt32BE(g + 4), gid0 = cmap.readUInt32BE(g + 8);
        for (let c = start; c <= end; c++) if (gid0 + (c - start) !== 0) out.add(c);
      }
    }
  }
  return out;
}

// --- planning ------------------------------------------------------------------------------

const chars = usedChars(source);
const cjkChars = chars.filter(isCjk);
const requests = requestedFamilies(source);
const known = new Map(Object.entries(table.families)); // "Noto Serif SC" -> entry
const cjkRequested = [...requests].filter(([name]) => known.has(name));
const unknownCjk = [...requests.keys()].filter((n) => !known.has(n) && /\b(SC|TC|HK|JP|KR|CJK)\b|^(ZCOOL|LXGW|Long Cang|Ma Shan Zheng)/.test(n));

const note = (s) => console.log(s);
const warn = (s) => console.warn('warning: ' + s);

function stripBlock(text) { return text.replace(BLOCK_RE, ''); }

if (!cjkRequested.length) {
  if (unknownCjk.length) warn(`no embedded-font data for: ${unknownCjk.join(', ')} (left on the Google Fonts link).`);
  if (cjkChars.length) {
    console.error('error: found no Google Fonts <link> / @import for a CJK family this pack knows (' + [...known.keys()].join(', ') + '). Add the CJK link first (see the prompt), then re-run.');
    process.exit(4);
  }
  note('No CJK font is requested and the deck has no CJK text: nothing to embed.');
  if (!dryRun && stripBlock(source) !== source) fs.writeFileSync(file, stripBlock(source));
  process.exit(0);
}
if (unknownCjk.length) warn(`no embedded-font data for: ${unknownCjk.join(', ')} (left on the Google Fonts link).`);
if (!cjkChars.length) {
  note('The deck has no CJK text: nothing to embed (the Google Fonts link stays as it is).');
  if (!dryRun && stripBlock(source) !== source) fs.writeFileSync(file, stripBlock(source));
  process.exit(0);
}

const plan = []; // { family, id, weight, k, file, range(str), ranges, sub:[cps] }
const coverage = new Map(); // family|weight -> Set(cp covered)
const missingWeights = [];
for (const [family, items] of cjkRequested) {
  const ent = known.get(family);
  const weights = new Set();
  for (const [lo, hi] of items) {
    const inside = ent.weights.filter((w) => w >= lo && w <= hi);
    if (inside.length) inside.forEach((w) => weights.add(w));
    else missingWeights.push(`${family} ${lo === hi ? lo : lo + '..' + hi}`);
  }
  for (const weight of [...weights].sort((a, b) => a - b)) {
    const cov = new Set();
    coverage.set(`${family}|${weight}`, cov);
    for (const k of ent.shardsByWeight[String(weight)]) {
      const rangeStr = ent.shards[k];
      const ranges = parseRange(rangeStr);
      const sub = chars.filter((cp) => rangeHas(ranges, cp));
      if (!sub.length) continue;
      sub.forEach((cp) => cov.add(cp));
      plan.push({ family, id: ent.id, version: ent.version, weight, k, file: `${ent.id}-${k}-${weight}-normal.woff2`, rangeStr, sub });
    }
  }
}
for (const m of missingWeights) warn(`${m} is not published for this family; the browser uses the nearest weight there is.`);

// --- download (site, then jsDelivr) -----------------------------------------------------------

async function fetchBytes(url) {
  const res = await fetch(url, { signal: AbortSignal.timeout(45000) });
  if (!res.ok) throw new Error(`HTTP ${res.status}`);
  const buf = Buffer.from(await res.arrayBuffer());
  if (buf.length < 100 || buf.subarray(0, 4).toString('latin1') !== 'wOF2') throw new Error('not a woff2 file');
  return buf;
}
function sourcesFor(p) {
  const list = [];
  if (table.siteBase) list.push(`${table.siteBase}fonts/cjk/${p.id}/${p.file}`);
  list.push(`${table.cdn}/@fontsource/${p.id}@${p.version}/files/${p.file}`);
  return list;
}
async function download(p) {
  const errors = [];
  for (let round = 0; round < 3; round++) {
    if (round) await new Promise((r) => setTimeout(r, 1500 * round));
    for (const url of sourcesFor(p)) {
      try { return await fetchBytes(url); } catch (e) { errors.push(`${url}: ${e.message}`); }
    }
  }
  throw new Error(errors.join('; '));
}

// fonttools' subsetter, if there is one: the pyftsubset command, or `python -m fontTools.subset`
// (pip's script folder is often not on PATH, e.g. on Windows).
let subsetter = null;
if (!noSubset) {
  const candidates = [['pyftsubset'], ...(process.platform === 'win32' ? [['pyftsubset.exe'], ['py', '-3', '-m', 'fontTools.subset']] : []), ['python3', '-m', 'fontTools.subset'], ['python', '-m', 'fontTools.subset']];
  for (const cmd of candidates) {
    try { execFileSync(cmd[0], [...cmd.slice(1), '--help'], { stdio: 'ignore', timeout: 30000 }); subsetter = cmd; break; } catch { /* not available */ }
  }
}
function trySubset(bytes, cps) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'sc-cjk-'));
  try {
    const inp = path.join(dir, 'in.woff2');
    const out = path.join(dir, 'out.woff2');
    fs.writeFileSync(inp, bytes);
    execFileSync(subsetter[0], [...subsetter.slice(1), inp, `--unicodes=${cps.map((c) => c.toString(16)).join(',')}`, '--flavor=woff2', '--layout-features=*', `--output-file=${out}`], { stdio: 'ignore', timeout: 60000 });
    const small = fs.readFileSync(out);
    return small.length > 0 && small.length < bytes.length ? small : null;
  } catch { return null; } finally { fs.rmSync(dir, { recursive: true, force: true }); }
}

async function pool(items, size, fn) {
  let i = 0;
  await Promise.all(Array.from({ length: Math.min(size, items.length) }, async () => {
    while (i < items.length) { const item = items[i++]; await fn(item); }
  }));
}

const failed = [];
let subsetCount = 0;
await pool(plan, 4, async (p) => {
  try { p.bytes = await download(p); } catch (e) { failed.push({ p, why: e.message }); return; }
  p.fullSize = p.bytes.length;
  // What the shard really contains (its ranges are Google's slicing; trust the font file, not the range).
  let have;
  try { have = woff2Cmap(p.bytes); } catch (e) { failed.push({ p, why: `unreadable font file: ${e.message}` }); p.bytes = null; return; }
  p.present = p.sub.filter((cp) => have.has(cp));
  if (!p.present.length) { p.bytes = null; return; } // the range names characters the file does not contain
  if (subsetter && p.present.length) {
    const small = trySubset(p.bytes, p.present);
    let got = null;
    try { got = small ? woff2Cmap(small) : null; } catch { /* unreadable: keep the whole shard */ }
    // A subset is only used when it provably holds every character it is meant to.
    if (got && p.present.every((cp) => got.has(cp))) { p.bytes = small; p.subset = true; subsetCount++; }
  }
});

// --- verify coverage -----------------------------------------------------------------------------

const embedded = plan.filter((p) => p.bytes);
const embeddedCov = new Map(); // family -> Set(cp)
for (const p of embedded) {
  if (!embeddedCov.has(p.family)) embeddedCov.set(p.family, new Set());
  p.present.forEach((cp) => embeddedCov.get(p.family).add(cp));
}
const uncovered = []; // covered by no embedded family at all
const partial = new Map(); // family -> [cp] CJK chars this family lacks
for (const cp of cjkChars) {
  const owners = [...embeddedCov].filter(([, s]) => s.has(cp)).map(([f]) => f);
  if (!owners.length) uncovered.push(cp);
}
for (const [family] of cjkRequested) {
  const s = embeddedCov.get(family) ?? new Set();
  const lack = cjkChars.filter((cp) => !s.has(cp));
  if (lack.length) partial.set(family, lack);
}
// A shard whose download failed leaves its characters to the Google Fonts link; not "uncovered" by the font itself.
const lostToDownload = new Set();
for (const { p } of failed) p.sub.forEach((cp) => lostToDownload.add(cp));
const trulyUncovered = uncovered.filter((cp) => !lostToDownload.has(cp));

// --- write the block -------------------------------------------------------------------------------

const b64 = (b) => b.toString('base64');
function buildBlock() {
  const rows = [];
  const byFamily = [...new Set(embedded.map((p) => p.family))].sort();
  for (const family of byFamily) {
    for (const p of embedded.filter((q) => q.family === family).sort((a, b) => a.weight - b.weight || a.k.localeCompare(b.k, 'en', { numeric: true }))) {
      const range = p.subset ? formatRange(p.present) : p.rangeStr;
      rows.push(`@font-face{font-family:'${family}';font-style:normal;font-weight:${p.weight};font-display:swap;src:url(data:font/woff2;base64,${b64(p.bytes)}) format('woff2');unicode-range:${range};}`);
    }
  }
  const fams = byFamily.map((f) => `${f} (${[...new Set(embedded.filter((p) => p.family === f).map((p) => p.weight))].join('/')})`).join(', ');
  return `${BEGIN}\n<style>/* CJK fonts embedded by embed-cjk.mjs: ${fams}; unicode-range slices of the fonts, SIL OFL 1.1 (see fonts/cjk-licenses/ in the pack) */\n${rows.join('\n')}\n</style>\n${END}\n`;
}

function insertBlock(text, block) {
  const clean = stripBlock(text);
  const i = clean.search(/<\/head\s*>/i);
  if (i >= 0) return clean.slice(0, i) + block + clean.slice(i);
  const j = clean.search(/<body[\s>]/i);
  if (j >= 0) return clean.slice(0, j) + block + clean.slice(j);
  return block + clean;
}

let added = 0;
if (embedded.length) {
  const block = buildBlock();
  added = Buffer.byteLength(block);
  if (!dryRun) {
    let out = insertBlock(source, block);
    if (hadBom && out.charCodeAt(0) !== 0xfeff) out = '\ufeff' + out;
    fs.writeFileSync(file, out);
  }
}

// --- summary ---------------------------------------------------------------------------------------------

const kb = (n) => (n / 1024).toFixed(n < 10240 ? 1 : 0) + ' KB';
const cpStr = (cp) => `${String.fromCodePoint(cp)} (U+${cp.toString(16).toUpperCase().padStart(4, '0')})`;
note(`${dryRun ? '[dry run] ' : ''}Deck: ${file}`);
note(`Characters: ${chars.length} distinct, of which ${cjkChars.length} CJK (letters, kana, hangul, full-width and CJK punctuation).`);
for (const family of [...new Set(plan.map((p) => p.family))].sort()) {
  const rowsF = plan.filter((p) => p.family === family);
  const weights = [...new Set(rowsF.map((p) => p.weight))].sort((a, b) => a - b);
  const total = embedded.filter((p) => p.family === family).reduce((s, p) => s + p.bytes.length, 0);
  note(`  ${family}: weights ${weights.join(', ')}; ${rowsF.length} shard(s), ${kb(total)} as woff2`);
}
note(`Added to the deck: ${kb(added)} (base64)${subsetter ? `; ${subsetCount}/${embedded.length} shard(s) cut down to the used characters with pyftsubset` : '; whole shards (install fonttools + brotli for pyftsubset to shrink them)'}.`);
for (const [family, lack] of partial) {
  if (lack.some((cp) => !trulyUncovered.includes(cp) && !lostToDownload.has(cp))) {
    const list = lack.filter((cp) => !trulyUncovered.includes(cp) && !lostToDownload.has(cp));
    warn(`${family} has no glyph for ${list.length} character(s) that other embedded families have: ${list.slice(0, 12).map(cpStr).join(' ')}${list.length > 12 ? ' …' : ''} (they use the next font in the stack, as with the Google Fonts link).`);
  }
}
if (failed.length) {
  console.error(`\nERROR: ${failed.length} shard(s) could not be downloaded; the deck's Google Fonts link remains the source for their characters:`);
  for (const f of failed.slice(0, 8)) console.error(`  ${f.p.family} ${f.p.weight} ${f.p.file}: ${f.why.slice(0, 160)}`);
  if (failed.length > 8) console.error(`  … and ${failed.length - 8} more`);
}
if (trulyUncovered.length) {
  console.error(`\nERROR: no embedded font has a glyph for ${trulyUncovered.length} CJK character(s): ${trulyUncovered.slice(0, 20).map(cpStr).join(' ')}${trulyUncovered.length > 20 ? ' …' : ''}`);
  console.error('They fall back to system fonts. Replace them with characters the font has, or accept the fallback and say so in your final reply.');
}
if (!trulyUncovered.length && !failed.length) note('Coverage OK: every CJK character is in an embedded font shard.');
process.exit(trulyUncovered.length ? 2 : failed.length ? 3 : 0);
