const noSubset = flag('--no-subset');
const rangesPath = opt('--ranges') ?? path.join(HERE, 'cjk-ranges.json');
const [file] = args;
if (!file || file.startsWith('-')) {
  console.error('usage: node fonts/embed-cjk.mjs <deck.html> [--dry-run] [--no-subset] [--ranges <cjk-ranges.json>]');
  process.exit(1);
}

